bool isCompletionShell(std::string_view shell) {
    return shell == "bash" || shell == "zsh" || shell == "powershell";
}

std::string completionScript(std::string_view shell) {
    if (shell == "bash") return bashScript();
    if (shell == "zsh") return zshScript();
    if (shell == "powershell") return powershellScript();
    return {};
}

