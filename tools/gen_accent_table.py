#!/usr/bin/env python3
"""Generate src/AccentTable.inc: precomposed Latin letters -> ASCII base letter.

Usage: python3 tools/gen_accent_table.py > src/AccentTable.inc
"""
import unicodedata

RANGES = [(0x00C0, 0x024F), (0x1E00, 0x1EFF)]
EXTRA = {0x00D8: "O", 0x00F8: "o", 0x0110: "D", 0x0111: "d", 0x0141: "L", 0x0142: "l"}

table = dict(EXTRA)
for lo, hi in RANGES:
    for cp in range(lo, hi + 1):
        decomposed = unicodedata.normalize("NFD", chr(cp))
        base = decomposed[0]
        if len(decomposed) > 1 and base.isascii() and base.isalpha():
            table[cp] = base

print("// Generated by tools/gen_accent_table.py - do not edit by hand.")
print("// Sorted by code point; used with binary search.")
for cp in sorted(table):
    print(f"{{0x{cp:04X}, U'{table[cp]}'}},")
