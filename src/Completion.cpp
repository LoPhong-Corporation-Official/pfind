std::vector<std::string> split(std::string_view text) {
    std::vector<std::string> words;
    std::istringstream stream{std::string(text)};
    std::string word;
    while (stream >> word) {
        words.push_back(word);
    }
    return words;
}

std::string replaceAll(std::string text, const std::string& from, const std::string& to) {
    for (std::size_t pos = 0; (pos = text.find(from, pos)) != std::string::npos; pos += to.size()) {
        text.replace(pos, from.size(), to);
    }
    return text;
}

std::string zshEscape(std::string_view text) {
    std::string out;
    for (const char c : text) {
        if (c == '\'') {
            out += "'\\''";
        } else if (c == '[' || c == ']' || c == ':' || c == '\\') {
            out += '\\';
            out += c;
        } else {
            out += c;
        }
    }
    return out;
}

std::string psEscape(std::string_view text) {
    std::string out;
    for (const char c : text) {
        out += c;
        if (c == '\'') {
            out += '\'';
        }
    }
    return out;
}

std::string bashScript() {
    std::string allOptions;
    std::string choiceCases;
    std::string freeNames;

    for (const OptionSpec& spec : optionSpecs()) {
        if (!spec.shortName.empty()) {
            allOptions += std::string(spec.shortName) + " ";
        }
        allOptions += std::string(spec.longName) + " ";

        if (spec.valueName.empty()) {
            continue;
        }

        std::string names = spec.shortName.empty()
            ? std::string(spec.longName)
            : std::string(spec.shortName) + "|" + std::string(spec.longName);

        if (!spec.choices.empty()) {
            choiceCases += "        " + names + ")\n" +
                           "            COMPREPLY=( $(compgen -W \"" + std::string(spec.choices) +
                           "\" -- \"$cur\") )\n            return 0 ;;\n";
        } else {
            freeNames += (freeNames.empty() ? "" : "|") + names;
        }
    }

    std::string script = R"BASH(# bash completion for pfind
# Generated by: pfind --completion bash
# Install:      pfind --completion bash > ~/.local/share/bash-completion/completions/pfind
#               (or:  source <(pfind --completion bash)  in ~/.bashrc)
_pfind() {
    local cur prev
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"
    if [[ "$cur" == "=" ]]; then cur=""; fi
    if [[ "$prev" == "=" ]]; then prev="${COMP_WORDS[COMP_CWORD-2]}"; fi

    case "$prev" in
@CHOICES@        @FREE@)
            return 0 ;;
    esac

    if [[ "$cur" == -* ]]; then
        COMPREPLY=( $(compgen -W "@OPTIONS@" -- "$cur") )
        return 0
    fi

    # The first positional argument is the directory; the others are patterns (free text).
    COMPREPLY=( $(compgen -d -- "$cur") )
    if type compopt >/dev/null 2>&1; then compopt -o filenames 2>/dev/null; fi
    return 0
}
complete -F _pfind pfind
)BASH";

    script = replaceAll(script, "@CHOICES@", choiceCases);
    script = replaceAll(script, "@FREE@", freeNames);
    script = replaceAll(script, "@OPTIONS@", allOptions);
    return script;
}

std::string zshScript() {
    std::string script =
        "#compdef pfind\n"
        "# zsh completion for pfind\n"
        "# Generated by: pfind --completion zsh\n"
        "# Install:      pfind --completion zsh > \"${fpath[1]}/_pfind\"   (then restart zsh)\n"
        "_arguments -S \\\n";

    for (const OptionSpec& spec : optionSpecs()) {
        const bool valued = !spec.valueName.empty();
        const std::string shortName(spec.shortName);
        const std::string longName(spec.longName);

        std::string valueSpec;
        if (valued) {
            valueSpec = ":" + std::string(spec.valueName) + ":";
            if (!spec.choices.empty()) {
                valueSpec += "(" + std::string(spec.choices) + ")";
            }
        }

        const std::string description = "[" + zshEscape(spec.description) + "]" + valueSpec;
        const std::string exclusion = shortName.empty() ? longName : shortName + " " + longName;

        std::string line = "  ";
        if (!shortName.empty()) {
            line += spec.repeatable ? "'*'" : "'(" + exclusion + ")'";
            line += "{" + shortName + (valued ? "+" : "") + "," + longName + (valued ? "=-" : "") + "}";
            line += "'" + description + "'";
        } else {
            line += "'" + std::string(spec.repeatable ? "*" : "(" + exclusion + ")") + longName +
                    (valued ? "=-" : "") + description + "'";
        }
        script += line + " \\\n";
    }

    script += "  '1:directory:_files -/' \\\n  '*:pattern:'\n";
    return script;
}

std::string powershellScript() {
    std::string entries;
    for (const OptionSpec& spec : optionSpecs()) {
        std::string choices = "@()";
        if (!spec.choices.empty()) {
            choices = "@(";
            const auto words = split(spec.choices);
            for (std::size_t i = 0; i < words.size(); ++i) {
                choices += (i ? "," : "") + std::string("'") + words[i] + "'";
            }
            choices += ")";
        }

        entries += "        @{ Name = '" + std::string(spec.longName) + "'; Short = '" +
                   std::string(spec.shortName) + "'; Value = " +
                   (spec.valueName.empty() ? "$false" : "$true") + "; Choices = " + choices +
                   "; Description = '" + psEscape(spec.description) + "' }\n";
    }

    std::string script = R"PS(# PowerShell completion for pfind
# Generated by: pfind --completion powershell
# Install:      pfind --completion powershell | Out-String | Invoke-Expression
#               (add that line to your $PROFILE to make it permanent)
Register-ArgumentCompleter -Native -CommandName pfind -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)

    $options = @(
@ENTRIES@    )

    # Words typed so far (without the program name and without the word being completed).
    $words = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object { $_.ToString() })
    if ($wordToComplete -ne '' -and $words.Count -gt 0) {
        $words = if ($words.Count -gt 1) { @($words[0..($words.Count - 2)]) } else { @() }
    }
    $previous = if ($words.Count -gt 0) { $words[$words.Count - 1] } else { '' }

    $owner = $options | Where-Object { $_.Value -and ($_.Name -eq $previous -or ($_.Short -ne '' -and $_.Short -eq $previous)) } | Select-Object -First 1
    if ($owner) {
        # The previous word is an option that takes a value.
        foreach ($choice in $owner.Choices) {
            if ($choice -like "$wordToComplete*") {
                [System.Management.Automation.CompletionResult]::new($choice, $choice, 'ParameterValue', $choice)
            }
        }
        return
    }

    if ($wordToComplete -like '-*') {
        foreach ($option in $options) {
            foreach ($name in @($option.Name, $option.Short) | Where-Object { $_ -ne '' }) {
                if ($name -like "$wordToComplete*") {
                    [System.Management.Automation.CompletionResult]::new($name, $name, 'ParameterName', $option.Description)
                }
            }
        }
    }
    # Anything else (directory, patterns): fall back to PowerShell's default file completion.
}
)PS";

    return replaceAll(script, "@ENTRIES@", entries);
}

